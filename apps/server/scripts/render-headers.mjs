// Renders apps/site/security-headers.json (the single source for response headers) into nginx snippets.
// The same JSON feeds the failover Worker later, so mirror responses match the origin.
//
//   node apps/server/scripts/render-headers.mjs          write the two snippets in apps/server/nginx/
//   node apps/server/scripts/render-headers.mjs --check  exit 1 if a committed file is out of date
//
// Two header sets come out of one file:
//   security-headers.conf   every page and asset: strict CSP, no inline script;
//   embed-headers.conf      /embeds/*.html only (the json's `embeds` object): author-supplied HTML with inline script,
//                           contained by a CSP `sandbox`, no network and no remote resources.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = (p) => fileURLToPath(new URL(p, import.meta.url));
export const SOURCE = here('../../site/security-headers.json');
export const TARGET = here('../nginx/security-headers.conf');
export const EMBED_TARGET = here('../nginx/embed-headers.conf');

/** nginx double-quoted string: escape backslash, quote and `$` (which nginx would treat as a variable). */
const q = (v) => '"' + String(v).replace(/[\\"$]/g, (c) => '\\' + c) + '"';

function lines(headers, note) {
  const out = [
    `# GENERATED by apps/server/scripts/render-headers.mjs from apps/site/security-headers.json (${note}). Do not edit.`,
    '# `always` so error pages carry the headers too.',
  ];
  for (const [name, value] of Object.entries(headers)) {
    if (name.startsWith('_')) continue; // _comment
    if (typeof value === 'object' && value !== null) continue; // a nested header set, rendered separately
    if (!/^[A-Za-z][A-Za-z0-9-]*$/.test(name)) throw new Error(`bad header name ${name}`);
    if (/[\r\n]/.test(String(value))) throw new Error(`header ${name} contains a line break`);
    out.push(`add_header ${name} ${q(value)} always;`);
  }
  return out.join('\n') + '\n';
}

export const render = (json) => lines(json, 'top-level headers');

export function renderEmbeds(json) {
  if (!json.embeds || typeof json.embeds !== 'object') throw new Error('security-headers.json has no `embeds` header set');
  const csp = String(json.embeds['Content-Security-Policy'] ?? '');
  // The embed policy is what makes arbitrary author HTML safe to serve from the site's own origin. Refuse to render
  // one that has lost any of its three guarantees.
  if (!/(^|;)\s*sandbox(\s|;|$)/.test(csp)) throw new Error('embeds CSP must contain a `sandbox` directive');
  if (/sandbox[^;]*allow-same-origin/.test(csp)) throw new Error('embeds CSP must not allow-same-origin');
  if (!/connect-src 'none'/.test(csp)) throw new Error("embeds CSP must contain connect-src 'none'");
  return lines(json.embeds, 'embeds');
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const json = JSON.parse(readFileSync(SOURCE, 'utf8'));
  const outputs = [
    [TARGET, render(json)],
    [EMBED_TARGET, renderEmbeds(json)],
  ];
  if (process.argv.includes('--check')) {
    let bad = false;
    for (const [target, out] of outputs) {
      let current = '';
      try {
        current = readFileSync(target, 'utf8');
      } catch {}
      if (current !== out) {
        console.error(`render-headers: ${target} is out of date; run \`node apps/server/scripts/render-headers.mjs\``);
        bad = true;
      }
    }
    if (bad) process.exit(1);
    console.log('render-headers: the nginx header snippets match security-headers.json');
  } else {
    for (const [target, out] of outputs) writeFileSync(target, out);
    console.log(`render-headers: wrote ${outputs.map(([t]) => t).join(' and ')}`);
  }
}
