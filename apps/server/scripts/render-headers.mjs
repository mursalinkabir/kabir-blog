// Renders apps/site/security-headers.json (the single source for response headers) into an nginx snippet.
// The same JSON feeds the failover Worker later, so mirror responses match the origin.
//
//   node apps/server/scripts/render-headers.mjs          write apps/server/nginx/security-headers.conf
//   node apps/server/scripts/render-headers.mjs --check  exit 1 if the committed file is out of date
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = (p) => fileURLToPath(new URL(p, import.meta.url));
export const SOURCE = here('../../site/security-headers.json');
export const TARGET = here('../nginx/security-headers.conf');

/** nginx double-quoted string: escape backslash, quote and `$` (which nginx would treat as a variable). */
const q = (v) => '"' + String(v).replace(/[\\"$]/g, (c) => '\\' + c) + '"';

export function render(json) {
  const lines = [
    '# GENERATED by apps/server/scripts/render-headers.mjs from apps/site/security-headers.json. Do not edit.',
    '# `always` so error pages carry the headers too.',
  ];
  for (const [name, value] of Object.entries(json)) {
    if (name.startsWith('_')) continue; // _comment
    if (!/^[A-Za-z][A-Za-z0-9-]*$/.test(name)) throw new Error(`bad header name ${name}`);
    if (/[\r\n]/.test(String(value))) throw new Error(`header ${name} contains a line break`);
    lines.push(`add_header ${name} ${q(value)} always;`);
  }
  return lines.join('\n') + '\n';
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const out = render(JSON.parse(readFileSync(SOURCE, 'utf8')));
  if (process.argv.includes('--check')) {
    let current = '';
    try {
      current = readFileSync(TARGET, 'utf8');
    } catch {}
    if (current !== out) {
      console.error(
        'render-headers: apps/server/nginx/security-headers.conf is out of date; run `node apps/server/scripts/render-headers.mjs`',
      );
      process.exit(1);
    }
    console.log('render-headers: security-headers.conf matches security-headers.json');
  } else {
    writeFileSync(TARGET, out);
    console.log(`render-headers: wrote ${TARGET}`);
  }
}
